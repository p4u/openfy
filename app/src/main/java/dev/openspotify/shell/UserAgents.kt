package dev.openspotify.shell

import androidx.webkit.UserAgentMetadata

/** The two browser identities compared by hypothesis H1 (DESIGN §2.2). */
enum class IdentityArm(val label: String) {
    MOBILE("Chrome Mobile"),
    DESKTOP("Desktop site"),
}

/** Pure construction of the UA string and UA-CH metadata, so it can be unit tested on the JVM. */
object UserAgents {
    private val chromeVersion = Regex("""Chrome/(\d+)\.""")

    /** Chromium major version from WebView's default UA, e.g. `...Chrome/131.0.6778.200 ...` -> 131. */
    fun chromiumMajor(defaultUa: String): Int? =
        chromeVersion.find(defaultUa)?.groupValues?.get(1)?.toIntOrNull()

    /** Chrome's reduced UA for each arm. The major version is the real one, never spoofed. */
    fun build(arm: IdentityArm, major: Int): String = when (arm) {
        IdentityArm.MOBILE ->
            "Mozilla/5.0 (Linux; Android 10; K) AppleWebKit/537.36 (KHTML, like Gecko) " +
                "Chrome/$major.0.0.0 Mobile Safari/537.36"
        IdentityArm.DESKTOP ->
            "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) " +
                "Chrome/$major.0.0.0 Safari/537.36"
    }
}

object UaMetadataFactory {
    private const val WEBVIEW_BRAND = "Android WebView"
    private const val CHROME_BRAND = "Google Chrome"

    /** False when the default metadata has no "Android WebView" brand, i.e. the rewrite would be a no-op. */
    fun hasWebViewBrand(base: UserAgentMetadata): Boolean = base.brandVersionList.any { it.brand == WEBVIEW_BRAND }

    /** `brand/majorVersion` pairs for the startup log. */
    fun describeBrands(metadata: UserAgentMetadata): String =
        metadata.brandVersionList.joinToString(prefix = "[", postfix = "]") { "${it.brand}/${it.majorVersion}" }

    /**
     * Rebuilds the metadata WebView generated by default. The single brand list feeds both `Sec-CH-UA`
     * and `Sec-CH-UA-Full-Version-List`, so one substitution covers both. The grease entry and all
     * versions stay exactly as Chromium produced them.
     */
    fun forArm(base: UserAgentMetadata, arm: IdentityArm): UserAgentMetadata {
        val brands = base.brandVersionList.map {
            if (it.brand == WEBVIEW_BRAND) {
                UserAgentMetadata.BrandVersion.Builder(it).setBrand(CHROME_BRAND).build()
            } else {
                it
            }
        }
        val builder = UserAgentMetadata.Builder(base).setBrandVersionList(brands)
        when (arm) {
            IdentityArm.MOBILE -> builder.setPlatform("Android").setMobile(true)
            IdentityArm.DESKTOP -> builder
                .setPlatform("Linux")
                .setMobile(false)
                .setModel("")
                .setPlatformVersion("")
        }
        return builder.build()
    }
}
